const values = { name: raw.name, from: raw.from, age: ageNow(raw.birthDate) }
values.ordinal = ordinal(values.age)

const fill = (v) =>
  typeof v === 'string'
    ? v.replace(/\{(\w+)\}/g, (m, key) => values[key] ?? m)
    : Array.isArray(v)
      ? v.map(fill)
      : v && typeof v === 'object'
        ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, fill(x)]))
        : v

export const config = fill(raw)
export const age = values.age
